from pathlib import Path
from collections import Counter
import re

import joblib
from flask import Flask, jsonify, request

BASE_DIR = Path(__file__).resolve().parent
MODEL_PATH = BASE_DIR / "variant_classifier.joblib"

app = Flask(__name__)
app.config["MAX_CONTENT_LENGTH"] = 25 * 1024 * 1024  # 25 MB upload limit

# Standard IUPAC nucleotide symbols. Ambiguous symbols are normalized to N for
# the model, while their original count is retained for quality reporting.
IUPAC = set("ACGTUNRYKMSWBDHV")
AMBIGUOUS_IUPAC = set("NRYKMSWBDHVU")
TO_N = str.maketrans({base: "N" for base in "RYKMSWBDHVU"})

_model = None


def load_model():
    global _model
    if _model is None:
        if not MODEL_PATH.is_file():
            raise FileNotFoundError(
                f"Model file not found at {MODEL_PATH}. "
                "Place variant_classifier.joblib beside pathogentwin_api.py."
            )
        _model = joblib.load(MODEL_PATH)
    return _model


def parse_single_fasta(raw_bytes):
    try:
        text = raw_bytes.decode("utf-8-sig")
    except UnicodeDecodeError as exc:
        raise ValueError("The uploaded file must be a text FASTA file.") from exc

    header = None
    chunks = []
    records = []

    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line:
            continue
        if line.startswith(">"):
            if header is not None:
                records.append((header, "".join(chunks)))
            header = line[1:].strip() or f"Sequence {len(records) + 1}"
            chunks = []
        else:
            if header is None:
                raise ValueError("Invalid FASTA: sequence data appears before a > header.")
            chunks.append(re.sub(r"\s+", "", line).upper())

    if header is not None:
        records.append((header, "".join(chunks)))

    if not records:
        raise ValueError("No FASTA sequence was found.")
    if len(records) != 1:
        raise ValueError(
            f"This API expects one genome per file; found {len(records)} sequences."
        )

    header, sequence = records[0]
    if not sequence:
        raise ValueError("The FASTA sequence is empty.")

    invalid = sorted(set(sequence) - IUPAC)
    if invalid:
        raise ValueError("Unsupported sequence symbols: " + ", ".join(invalid))

    if len(sequence) < 100:
        raise ValueError("Sequence is too short for this whole-genome classifier.")

    original_ambiguous = sum(base not in "ACGT" for base in sequence)
    ambiguous_pct = 100.0 * original_ambiguous / len(sequence)
    n_pct = 100.0 * sequence.count("N") / len(sequence)
    gc_pct = 100.0 * (sequence.count("G") + sequence.count("C")) / len(sequence)

    # Convert U and IUPAC ambiguity codes to N before model input.
    model_sequence = sequence.translate(TO_N).replace("U", "N")

    return {
        "header": header,
        "sequence": model_sequence,
        "genome_length": len(sequence),
        "ambiguous_bases": original_ambiguous,
        "ambiguous_percentage": round(ambiguous_pct, 4),
        "n_percentage": round(n_pct, 4),
        "gc_percentage": round(gc_pct, 4),
    }


def feature_coverage(model, sequence):
    """Fraction of 5-mers recognized by the fitted CountVectorizer vocabulary."""
    try:
        vectorizer = model.named_steps["vectorizer"]
        analyzer = vectorizer.build_analyzer()
        kmers = list(analyzer(sequence))
        if not kmers:
            return 0.0
        vocabulary = vectorizer.vocabulary_
        known = sum(1 for kmer in kmers if kmer in vocabulary)
        return known / len(kmers)
    except Exception:
        # If the saved model has an unexpected structure, don't fail prediction
        # solely because this optional diagnostic is unavailable.
        return None


@app.get("/health")
def health():
    try:
        model = load_model()
        return jsonify({
            "status": "ok",
            "model_loaded": True,
            "classes": [str(x) for x in getattr(model, "classes_", [])],
        })
    except Exception as exc:
        return jsonify({"status": "error", "model_loaded": False, "error": str(exc)}), 500


@app.post("/predict")
def predict():
    uploaded = request.files.get("file")
    if uploaded is None:
        return jsonify({"status": "error", "message": "Missing upload field 'file'."}), 400
    if not uploaded.filename:
        return jsonify({"status": "error", "message": "No filename was provided."}), 400

    try:
        parsed = parse_single_fasta(uploaded.read())
        model = load_model()
        sequence = parsed["sequence"]

        warnings = [
            "Experimental model output only; this is not a formal lineage assignment.",
            "The classifier only represents Alpha, Beta, Gamma, and Omicron classes.",
        ]
        if parsed["ambiguous_percentage"] > 5:
            warnings.append(
                "More than 5% of bases are ambiguous; prediction may be unreliable."
            )

        coverage = feature_coverage(model, sequence)
        if coverage is not None and coverage < 0.10:
            warnings.append(
                "Very low training-vocabulary feature coverage. The class prediction "
                "is withheld because this sequence may be outside the model's learned representation."
            )
            return jsonify({
                "status": "success",
                "demo_mode": False,
                "variant": "Uncertain — insufficient feature coverage",
                "confidence": None,
                "feature_coverage": round(coverage * 100, 2),
                "genome_length": parsed["genome_length"],
                "n_percentage": parsed["n_percentage"],
                "ambiguous_percentage": parsed["ambiguous_percentage"],
                "ambiguous_bases": parsed["ambiguous_bases"],
                "mutation_count": 0,
                "mutations": [],
                "quality": {
                    "n_percentage": parsed["n_percentage"],
                    "ambiguous_percentage": parsed["ambiguous_percentage"],
                    "ambiguous_bases": parsed["ambiguous_bases"],
                    "gc_percentage": parsed["gc_percentage"],
                },
                "warnings": warnings,
                "evidence": [],
                "filename": uploaded.filename,
                "sequence_header": parsed["header"],
                "method": "Character 5-mer CountVectorizer + Logistic Regression",
            })

        prediction = str(model.predict([sequence])[0])
        confidence = None
        scores = []
        if hasattr(model, "predict_proba"):
            probabilities = model.predict_proba([sequence])[0]
            classes = [str(c) for c in model.classes_]
            ordered = sorted(
                zip(classes, probabilities), key=lambda pair: pair[1], reverse=True
            )
            confidence = float(ordered[0][1])
            scores = [
                {"class": label, "score": round(float(score) * 100, 2)}
                for label, score in ordered
            ]
            margin = float(ordered[0][1] - ordered[1][1]) if len(ordered) > 1 else 1.0
            # These are conservative display warnings, not calibrated clinical cutoffs.
            if confidence < 0.60 or margin < 0.15:
                warnings.append(
                    "Low separation between model scores. Treat the predicted class as uncertain; "
                    "scores are not calibrated probabilities of biological correctness."
                )

        if coverage is not None:
            if coverage < 0.25:
                warnings.append(
                    "Low training-vocabulary feature coverage; prediction may not generalize to this sequence."
                )

        return jsonify({
            "status": "success",
            "demo_mode": False,
            "variant": prediction,
            "confidence": confidence,
            "class_scores": scores,
            "feature_coverage": round(coverage * 100, 2) if coverage is not None else None,
            "genome_length": parsed["genome_length"],
            "n_percentage": parsed["n_percentage"],
            "ambiguous_percentage": parsed["ambiguous_percentage"],
            "ambiguous_bases": parsed["ambiguous_bases"],
            "mutation_count": 0,
            "mutations": [],
            "quality": {
                "n_percentage": parsed["n_percentage"],
                "ambiguous_percentage": parsed["ambiguous_percentage"],
                "ambiguous_bases": parsed["ambiguous_bases"],
                "gc_percentage": parsed["gc_percentage"],
            },
            "warnings": warnings,
            "evidence": [],
            "filename": uploaded.filename,
            "sequence_header": parsed["header"],
            "method": "Character 5-mer CountVectorizer + Logistic Regression",
        })
    except (ValueError, FileNotFoundError) as exc:
        return jsonify({"status": "error", "message": str(exc)}), 400 if isinstance(exc, ValueError) else 500
    except Exception as exc:
        app.logger.exception("Prediction failed")
        return jsonify({"status": "error", "message": f"Prediction failed: {exc}"}), 500


if __name__ == "__main__":
    # Local development server for project testing only.
    app.run(host="127.0.0.1", port=5000, debug=False)
